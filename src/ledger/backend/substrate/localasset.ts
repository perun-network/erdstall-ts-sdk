export function fungibleAsset(id: bigint): Uint8Array & { length: 32 }
{
	if(id > 0xffff || id < 0)
		throw new Error(`Expected uint16 asset ID, got ${id}`);
	return Uint8Array.of(
		0xff, 0x42, 0x41, 0x4a, 0x55, 0x4e, 0x5f, 0x4e,
		0x45, 0x54, 0x57, 0x4f, 0x52, 0x4b, 0x5f, 0x4f,
		0x4e, 0x5f, 0x4b, 0x55, 0x53, 0x41, 0x4d, 0x41,
		0x5f, 0x31, 0x33, 0x33, 0x37, 0xda,
		Number(id & 0xffn), Number((id >> 8n) & 0xffn)
	) as (Uint8Array & { length: 32 });
}

export function nftAsset(id: bigint): Uint8Array & { length: 32 }
{
	if(id > 0xffff || id < 0)
		throw new Error(`Expected uint16 asset ID, got ${id}`);

	return Uint8Array.of(
		0x77, 0x42, 0x41, 0x4a, 0x55, 0x4e, 0x5f, 0x4e,
		0x45, 0x54, 0x57, 0x4f, 0x52, 0x4b, 0x5f, 0x4f,
		0x4e, 0x5f, 0x4b, 0x55, 0x53, 0x41, 0x4d, 0x41,
		0x5f, 0x31, 0x33, 0x33, 0x37, 0xda,
		Number(id & 0xffn), Number((id >> 8n) & 0xffn)
	) as (Uint8Array & { length: 32 });
}